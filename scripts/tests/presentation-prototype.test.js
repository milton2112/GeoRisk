import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { parse } from 'yaml';
import { PUBLIC_FILES, PUBLIC_DIRS } from '../lib/public-assets.js';
import './presentation-lifecycle.test.js';
const workflow = parse(await fs.readFile('.github/workflows/presentation-prototype.yml', 'utf8'));
assert.deepEqual(workflow.permissions, { contents: 'read' });
assert.deepEqual(Object.keys(workflow.on).sort(), ['push', 'workflow_dispatch']);
assert.deepEqual(workflow.on.push.branches, ['codex/experiment/map-presentation-*']);
assert.equal(workflow.jobs['presentation-prototype']['timeout-minutes'], 10);
const steps = workflow.jobs['presentation-prototype'].steps;
const scan = steps.findIndex(step => step.id === 'security-scan');
const run = steps.findIndex(step => step.run === 'node scripts/diagnostics/runPresentationRecovery.js');
assert.ok(scan >= 0 && run > scan);
assert.equal(steps[scan].run, 'node scripts/checkSecurity.js --history');
assert.ok(steps.some(s => s.run === 'npx playwright install --with-deps --no-shell chromium'));
assert.ok(steps.every(s => !/deploy|pages/.test(s.uses || '')));
const upload = steps.find(step => step.uses?.startsWith('actions/upload-artifact@'));
assert.equal(upload.if, "always() && steps.security-scan.outcome == 'success'");
assert.equal(upload.with['retention-days'], 7);
assert.ok(!upload.with.path.includes('engine-prototype'));
const published = [...PUBLIC_FILES, ...PUBLIC_DIRS];
assert.ok(published.every(file => !/presentation-prototype|PresentationPrototype/.test(file)));
const runner = await fs.readFile('scripts/diagnostics/runPresentationPrototype.js', 'utf8');
assert.ok(runner.includes('timeoutMs: 30000'));
assert.ok(runner.includes('timeoutMs: 90000'));
assert.ok(runner.includes('failure.json'));
const controller = await fs.readFile('scripts/diagnostics/controlPresentationPrototype.js', 'utf8');
assert.ok(controller.includes('getPerformanceInputHash(root)'));
assert.ok(controller.includes('2 * 1024 ** 2 - 16384'));
assert.ok(controller.includes('events.length + selected.length > 5000'));
assert.ok(controller.includes('await stopTrace()'));
assert.ok(!controller.includes('enable-unsafe') && !controller.includes('use-angle'));
assert.ok(controller.includes('capture.sha256 === captures[0].sha256') || controller.includes('c.sha256 === captures[0].sha256'));
assert.ok(controller.includes("eventObserver?.observe({ type: 'event', buffered: true, durationThreshold: 16 })"));
assert.ok(controller.includes('page.mouse.click(inputPoint.x, inputPoint.y)'));
assert.ok(controller.includes('two real pointer clicks must emit trusted pointer and click events'));
assert.ok(controller.includes('eventTimings.length <= 16'));
assert.ok(controller.includes("entry.name === 'click' && entry.target?.id === 'toggle-tools-panel'"));
assert.ok(controller.includes('viewer.__geoRiskRenderRecovery.dispose()'));
assert.ok(controller.includes('renderRecoveryDisposedForDiagnostic: true'));
const interactionsRunner = await fs.readFile('scripts/diagnostics/runPresentationInteractions.js', 'utf8');
assert.ok(interactionsRunner.includes('timeoutMs: 30000'));
assert.ok(interactionsRunner.includes('timeoutMs: 90000'));
assert.ok(interactionsRunner.includes('interactions-failure.json'));
assert.deepEqual(upload.with.path.trim().split('\n'), ['reports/presentation-prototype/build.json',
  'reports/presentation-prototype/recovery.json', 'reports/presentation-prototype/recovery-failure.json',
  'reports/presentation-prototype/recovery.png']);
const recoveryRunner = await fs.readFile('scripts/diagnostics/runPresentationRecovery.js', 'utf8');
assert.ok(recoveryRunner.includes('timeoutMs: 30000'));
assert.ok(recoveryRunner.includes('timeoutMs: 90000'));
assert.ok(recoveryRunner.includes('recovery-failure.json'));
// Import must expose the real assertions without starting a browser or replacing the normal checkpoint.
const checkpoint = await fs.readFile('reports/critical-browser-e2e.json').catch(error => {
  if (error.code !== 'ENOENT') throw error;
  return null;
});
const shared = await import('./critical-browser-e2e.test.js');
assert.equal(typeof shared.clickCountryOnMap, 'function');
assert.equal(typeof shared.closeCriticalTileCache, 'function');
assert.equal(typeof shared.testRenderRecovery, 'function');
assert.deepEqual(await fs.readFile('reports/critical-browser-e2e.json').catch(error => {
  if (error.code !== 'ENOENT') throw error;
  return null;
}), checkpoint, 'import must preserve ordinary release evidence');
shared.closeCriticalTileCache();
console.log('presentation-prototype.test.js ok: isolated trigger, unchanged regular Chromium, bounded process/evidence, production exclusion');
